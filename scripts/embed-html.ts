import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const rootDir = join(import.meta.dir, "..");
const distHtmlPath = join(rootDir, "dist", "index.html");
const targetTsPath = join(rootDir, "src", "server", "embedded-html.ts");

if (existsSync(distHtmlPath)) {
  const html = readFileSync(distHtmlPath, "utf-8");
  const tsContent = `// Auto-generated by scripts/embed-html.ts - DO NOT EDIT MANUALLY\nexport const EMBEDDED_HTML = ${JSON.stringify(html)};\n`;
  writeFileSync(targetTsPath, tsContent, "utf-8");
  console.log("Successfully embedded dist/index.html into src/server/embedded-html.ts");
} else {
  console.error("dist/index.html not found, skipping embed");
}
